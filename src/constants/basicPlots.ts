export function getBasicPlotById(id: string): BasicPlotDefinition | undefined {
  return BASIC_PLOTS.find((p) => p.id === id);
}

export function getBasicPlotsByIds(ids?: string[]): BasicPlotDefinition[] {
  if (!ids || ids.length === 0) return [];
  return ids
    .map((id) => getBasicPlotById(id))
    .filter((p): p is BasicPlotDefinition => Boolean(p));
}

/**
 * Generates an architectural prompt directive for AI synopsis and chapter generation
 * explaining the combined structural requirements of the chosen plots.
 */
export function buildPlotPromptDirective(plotIds?: string[]): string {
  const plots = getBasicPlotsByIds(plotIds);
  if (plots.length === 0) {
    return '';
  }

  const sections = plots.map((p, idx) => {
    return `${idx + 1}. Шаблон «${p.title}» (${p.englishTitle}):
   • Суть: ${p.essence}
   • Описание: ${p.description}
   • Примеры: ${p.examples.join(', ')}
   • Ключевые сюжетные точки: ${p.narrativeBeats.join(' -> ')}`;
  });

  if (plots.length === 1) {
    return `
АРХИТЕКТУРА СЮЖЕТА (фундаментальный шаблон KnigAI):
${sections[0]}
Строго структурируй развитие событий, кульминацию и переломные моменты в соответствии с законами шаблона «${plots[0].title}».`;
  }

  return `
АРХИТЕКТУРА СЮЖЕТА (комбинация шаблонов KnigAI):
Данное произведение гармонично объединяет ${plots.length} фундаментальных сюжета: ${plots.map((p) => `«${p.title}»`).join(' + ')}.
${sections.join('\n\n')}
Требование: Сплети эти сюжетные линии в единую драматургию: совмещай внешние вызовы одного шаблона с внутренней трансформацией другого.`;
}
