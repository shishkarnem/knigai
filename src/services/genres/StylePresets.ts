export function getDefaultStyle(): BookStyleConfig {
  return {
    styleName: STYLE_PRESETS[0].styleName,
    proseVoice: STYLE_PRESETS[0].proseVoice,
    pacing: STYLE_PRESETS[0].pacing,
    vocabulary: STYLE_PRESETS[0].vocabulary,
    visualAesthetic: STYLE_PRESETS[0].visualAesthetic,
    customGuidelines: STYLE_PRESETS[0].customGuidelines,
  };
}

export function getStyleByName(name?: string): StylePresetItem | undefined {
  if (!name) return undefined;
  return STYLE_PRESETS.find((s) => s.styleName.toLowerCase() === name.toLowerCase() || s.id === name);
}
