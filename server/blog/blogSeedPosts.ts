function extractFileIdFromShortUrl(url: string): number | null {
  const m = String(url || '').match(/\/file\/(\d+)/);
  return m ? Number(m[1]) : null;
}

export async function ensureBlogSeedPosts(
  queryPg: QueryPgFn,
  imageResolver?: (spec: SeedBlogPostSpec, slot: 'cover' | 'inline1' | 'inline2') => Promise<string>
): Promise<void> {
  await ensureBlogSchema(queryPg);
  const blogFolderId = await ensureBlogFolderId(queryPg);

  // Check how many seed posts already exist
  const existingRes = await queryPg<{ slug: string }>(
    `SELECT slug FROM blog_posts;`
  );
  const existingSlugs = new Set((existingRes.rows || []).map((r) => String(r.slug)));

  // Also grab existing images from file_storage in "Блог и статьи" folder or fallback
  const existingFilesRes = await queryPg<{ id: number; name: string }>(
    `SELECT id, name FROM file_storage WHERE folder_id = $1 ORDER BY id ASC;`,
    [blogFolderId || -1]
  ).catch(() => ({ rows: [] as Array<{ id: number; name: string }> }));

  const fallbackPool = (existingFilesRes.rows || []).map((r) => `/file/${r.id}`);

  for (let i = 0; i < BLOG_SEED_SPECS.length; i++) {
    const spec = BLOG_SEED_SPECS[i];
    if (existingSlugs.has(spec.slug)) {
      continue;
    }

    let coverUrl = fallbackPool[(i * 3) % Math.max(1, fallbackPool.length)] || '';
    let img1Url = fallbackPool[(i * 3 + 1) % Math.max(1, fallbackPool.length)] || coverUrl;
    let img2Url = fallbackPool[(i * 3 + 2) % Math.max(1, fallbackPool.length)] || coverUrl;

    if (imageResolver) {
      coverUrl = await imageResolver(spec, 'cover');
      img1Url = await imageResolver(spec, 'inline1');
      img2Url = await imageResolver(spec, 'inline2');
    }

    const content = spec.contentTemplate
      .replace(/\{\{COVER\}\}/g, coverUrl)
      .replace(/\{\{IMG1\}\}/g, img1Url)
      .replace(/\{\{IMG2\}\}/g, img2Url);

    const uniqueSlug = await ensureUniqueSlug(queryPg, spec.slug);
    const coverFileId = extractFileIdFromShortUrl(coverUrl);

    await queryPg(
      `INSERT INTO blog_posts (
         slug, title, subtitle, excerpt, content_markdown, cover_image_url, cover_file_id,
         tags, seo_keywords, author_name, author_uid, status, published_at, updated_at
       ) VALUES ($1, $2, $3, $4, $5, $6, $7, $8::jsonb, $9, 'Редакция KnigAI', 10000000001, 'published', now() - ($10 || ' hours')::interval, now())
       ON CONFLICT (slug) DO NOTHING;`,
      [
        uniqueSlug,
        spec.title,
        spec.subtitle,
        spec.excerpt,
        content,
        coverUrl,
        coverFileId,
        JSON.stringify(spec.tags),
        spec.seo_keywords,
        String((BLOG_SEED_SPECS.length - i) * 6),
      ]
    ).catch((err) => {
      console.warn(`[KnigAI Blog Seed] Insert notice for ${spec.slug}:`, err);
    });
  }
}
